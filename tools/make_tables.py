# ---- T10 MuJoCo -------------------------------------------------------------
js = sorted(glob.glob(os.path.join(RES, "mujoco", "V*.json")))
if js:
    D = pd.DataFrame([json.load(open(f)) for f in js])
    D["grp"] = D.name.str[:2]
    D["law"] = D.algo.map(NAME)
    D["world"] = D.world.str.replace("swarm_world_", "").str.replace(".sdf", "")
    D["limits"] = np.where(D.kin, "on", "off")
    D["feedback"] = np.where(D.hold_err > 0, "on", "off")
    D["rms cm"] = 100 * D.formation_rms
    D["p95 cm"] = 100 * D.formation_err_p95
    D["max cm"] = 100 * D.formation_err_max
    D["pin mm"] = 1000 * D.pin_gap_max
    D["contact static/mover"] = D.contact_steps_static.astype(str) + " / " + D.contact_steps_mover.astype(str)
    D["planner rej"] = D.n_reject
    D["planner mover contact"] = D.coll_mover
    D["reached"] = D.reached_goal.map({True: "yes", False: "NO"})
    # the planner frame reaching B is not delivery: the robots must be there too
    D["load at B"] = np.where(D.reached_goal & (D.final_centroid_err < 1.0), "yes", "NO")
    D["final err m"] = D.final_centroid_err
    cols = ["law", "formation", "payload", "seed", "limits", "feedback", "reached", "load at B", "final err m", "total_time", "planner rej",
            "planner mover contact", "rms cm", "p95 cm", "max cm", "min_robot_gap_phys",
            "contact static/mover", "hold_steps", "pin mm", "payload_tilt_max_deg"]
    titles = {"V1": "laws x payload modes (AWS warehouse, square, limits on)",
              "V2": "formation shapes (s = 0.60 m)", "V3": "motion limits OFF", 
              "V4": "seeds 2-5, carried plate", "V5": "the MATLAB study's warehouse under physics",
              "V6": "formation feedback OFF (open-loop frame)"}
    for g, t in titles.items():
        d = D[D.grp == g]
        if len(d) == 0:
            continue
        L += [f"## T10-{g}. MuJoCo: {t}", ""]
        L += tbl(d[cols].rename(columns={"total_time": "time s", "min_robot_gap_phys": "min gap m",
                                         "hold_steps": "hold steps", "payload_tilt_max_deg": "tilt deg"}),
                 {"final err m": "{:.2f}", "time s": "{:.1f}", "rms cm": "{:.1f}", "p95 cm": "{:.1f}", "max cm": "{:.1f}",
                  "min gap m": "{:.2f}", "pin mm": "{:.1f}", "tilt deg": "{:.1f}"}) + [""]

