import glob
import json
import os

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
NAME = {"apf": "APF", "vfh": "VFH", "fgm": "FGM", "dwa": "DWA", "mpc": "MPC",
        "pvfh": "pVFH", "pvfh_filt": "pVFH+F", "pvfh_prob": "P-VFH"}
ORDER = ["apf", "vfh", "fgm", "dwa", "mpc", "pvfh", "pvfh_filt", "pvfh_prob"]
L = ["# Results tables (auto-generated by tools/make_tables.py)", ""]


def have(*p):
    return all(os.path.exists(x) for x in p)


def tbl(df, fmt=None):
    fmt = fmt or {}
    out = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(
            (fmt[c].format(r[c]) if c in fmt and pd.notna(r[c]) else str(r[c])) for c in df.columns) + " |")
    return out


# ---- T1 deterministic cross-check ------------------------------------------
