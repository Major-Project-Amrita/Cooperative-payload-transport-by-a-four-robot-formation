def summ(d):
    """Standard per-cell summary of a run table."""
    n = len(d)
    k = int(d.reached.sum())
    c = int((d.collisions > 0).sum()) if "collisions" in d else 0
    tr = d[d.reached == 1].total_time if "total_time" in d else []
    return dict(n=n, reach=rate(k, n), contact_runs=rate(c, n),
                contact_steps=mci(d.collisions, "{:.1f}"),
                min_gap=mci(d.min_clear - R, "{:.2f}"), time=mci(tr))


