def heat(d, rowkey, rows, laws, title, fname):
    plt = plt_setup()
    from matplotlib.colors import ListedColormap
    M = np.full((len(rows), len(laws)), np.nan)
    T = [["" for _ in laws] for _ in rows]
    for i, r in enumerate(rows):
        for j, a in enumerate(laws):
            x = d[(d[rowkey] == r) & (d.algo == a)]
            if len(x):
                M[i, j] = x.reached.mean()
                T[i][j] = f"{int(x.reached.sum())}/{len(x)}"
    fig, ax = plt.subplots(figsize=(1.0 * len(laws) + 2.2, 0.42 * len(rows) + 1.3))
    ax.imshow(M, cmap=ListedColormap(SEQ), vmin=0, vmax=1, aspect="auto")
    for i in range(len(rows)):
        for j in range(len(laws)):
            if T[i][j]:
                ax.text(j, i, T[i][j], ha="center", va="center", fontsize=7.5,
                        color="#ffffff" if M[i, j] > 0.55 else INK)
    ax.set_xticks(range(len(laws)), [NAME[a] for a in laws], rotation=30, ha="right")
    ax.set_yticks(range(len(rows)), rows)
    ax.grid(False)
    ax.set_title(title, loc="left", fontsize=10)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, fname), dpi=200)
    plt.close(fig)


