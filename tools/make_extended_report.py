def r2():
    fn, fp = (os.path.join(RES, "results_headless_exactgate.csv"),
              os.path.join(RES, "results_headless_phase.csv"))
    if not (os.path.exists(fn) and os.path.exists(fp)):
        return
    N, P = pd.read_csv(fn), pd.read_csv(fp)
    if len(P) < 50:
        return
    L.extend(["## R2. Randomised traffic phase (review step 2)", "",
              f"The full grid re-run with a random release time per mover and run "
              f"({len(P)} of {len(N)} rows complete). Same cells, seeds and sensor "
              "noise as the nominal-timetable grid (exact gate); only the traffic "
              "phase differs. `contact runs` = runs with at least one contact step.", ""])
    rows = []
    for a in ORDER:
        n, p = N[N.algo == a], P[P.algo == a]
        if not len(p):
            continue
        n = n[n.key.isin(p.key.str.replace("|ph1", "", regex=False))]
        for lab, d in (("nominal", n), ("random phase", p)):
            s = summ(d)
            rows.append(dict(law=NAME[a], traffic=lab, **s))
    L.extend(["### All experiments pooled, per law", ""])
    L.extend(tbl(rows, ["law", "traffic", "n", "reach", "contact_runs", "contact_steps",
                        "min_gap", "time"]))
    rows = []
    for e in sorted(P.exp.unique(), key=lambda s: int(s[1:])):
        n0 = N[N.exp == e]
        p0 = P[P.exp == e]
        n0 = n0[n0.key.isin(p0.key.str.replace("|ph1", "", regex=False))]
        rows.append(dict(exp=e, runs=len(p0),
                         reach_nominal=rate(int(n0.reached.sum()), len(n0)),
                         reach_phase=rate(int(p0.reached.sum()), len(p0)),
                         contact_runs_nominal=rate(int((n0.collisions > 0).sum()), len(n0)),
                         contact_runs_phase=rate(int((p0.collisions > 0).sum()), len(p0))))
    L.extend(["### Per experiment", ""])
    L.extend(tbl(rows, ["exp", "runs", "reach_nominal", "reach_phase",
                        "contact_runs_nominal", "contact_runs_phase"]))
    # failure categories under the random phase
    f = P[P.reached == 0]
    if len(f):
        cat = np.where(f.collisions > 0, "timeout with contact", "timeout, no contact (deadlock/livelock)")
        L.extend([f"Failed runs under the random phase: {len(f)}; "
                  + ", ".join(f"{c}: {int((cat == c).sum())}" for c in sorted(set(cat))), ""])
    # figure: dumbbell nominal vs phase per law, reach + contact-run rate
    plt = plt_setup()
    laws = [a for a in ORDER if a in set(P.algo)]
    fig, axs = plt.subplots(1, 2, figsize=(8.0, 0.36 * len(laws) + 1.2), sharey=True)
    for ax, (metric, lab) in zip(axs, ((lambda d: d.reached == 1, "goal reached"),
                                       (lambda d: d.collisions > 0, "runs with any contact"))):
        for i, a in enumerate(laws):
            n = N[(N.algo == a) & N.key.isin(P[P.algo == a].key.str.replace("|ph1", "", regex=False))]
            p = P[P.algo == a]
            vals = []
            for d, col, mk in ((n, "#2a78d6", "o"), (p, "#eb6834", "s")):
                k, m = int(metric(d).sum()), len(d)
                lo, hi = wilson(k, m)
                ax.plot([lo, hi], [i, i], color=col, lw=2, alpha=0.5, solid_capstyle="round")
                ax.plot(k / m, i, mk, color=col, ms=6, mec=SURF, mew=1.5)
                vals.append(k / m)
            ax.plot(vals, [i, i], color=INK2, lw=0.8, zorder=0)
        ax.set_xlabel(f"fraction of runs: {lab}")
        ax.set_xlim(-0.02, 1.02)
    axs[0].set_yticks(range(len(laws)), [NAME[a] for a in laws])
    axs[0].invert_yaxis()
    axs[1].plot([], [], "o", color="#2a78d6", label="nominal timetable")
    axs[1].plot([], [], "s", color="#eb6834", label="random traffic phase")
    axs[1].legend(loc="lower right")
    fig.suptitle("Traffic-phase randomisation, all grid experiments pooled (95 % Wilson)", x=0.01,
                 ha="left", fontsize=10)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "fig_phase_effect.png"), dpi=200)
    plt.close(fig)
    L.extend(["![Phase effect](../results/figures_ext/fig_phase_effect.png)", ""])


