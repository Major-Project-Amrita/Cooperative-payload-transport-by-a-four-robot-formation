"""Build the validation scenario from the AWS-style warehouse MJCF.

  worlds/aws_warehouse.xml  (MuJoCo scene, the physics world)
      -> worlds/swarm_world_awswh.sdf        2D slice at the robot height band
      -> worlds/dynamic_obstacles_awswh.json movers + waypoint route + start

MATLAB (sdf2world.m), the Python headless runner and the MuJoCo validation
all load these two files, so the three stacks see identical geometry, movers
and route.

Mission: pick the load up in the dock (A), carry it north up an aisle,
west along the cross-aisle and north into the west aisle (B).

Movers (kinematic, they never yield): a forklift crossing the dock zone in
front of the start, a cart working along one side of the first aisle, and a
picker walking in a side aisle next to the route. They are placed where a
2 m wide body CAN avoid them. A mover that walks straight through the 2.4 m
cross-aisle while the formation fills it makes contact unavoidable for any
local planner (tried first: every law, including MPC, was run into at the
intersection), which tests the scenario, not the steering law.
"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = os.path.join(ROOT, "src", "ros2_swarm_transport")
sys.path.insert(0, PKG)
from ros2_swarm_transport.geometry import load_dynamic_obstacles
from ros2_swarm_transport.mjcf_world import world_from_mjcf, world_to_sdf

W = os.path.join(PKG, "worlds")
START = [4.5, -9.6]
WAYPOINTS = [[2.8, -5.5], [2.8, 2.1], [-8.35, 2.1], [-8.35, 8.0]]
contract = {
    "comment": "Validation scenario on the AWS-style warehouse "
               "(worlds/aws_warehouse.xml). Same schema as dynamic_obstacles.json; "
               "'waypoints' is the global route, 'start' and 'scatter_radius' "
               "place the start ring.",
    "frame": "world", "dt": 0.1,
    "start": START, "scatter_radius": 1.8,
    "waypoints": WAYPOINTS,
    "movers": [
        {"name": "mover1", "shape": "box", "size": [0.7, 0.7], "radius": 0.0,
         "route": [[-7.5, -7.8], [7.5, -7.8]], "speed": 0.7, "t0": 0.0,
         "wait": 4.0, "loop": True},
        {"name": "mover2", "shape": "circle", "size": [0.5, 0.5], "radius": 0.25,
         "route": [[4.1, 0.0], [4.1, -6.0]], "speed": 0.4, "t0": 0.0,
         "wait": 5.0, "loop": True},
        {"name": "mover3", "shape": "circle", "size": [0.6, 0.6], "radius": 0.3,
         "route": [[-2.8, 4.6], [-2.8, 9.5]], "speed": 0.6, "t0": 0.0,
         "wait": 3.0, "loop": True},
    ],
}
cj = os.path.join(W, "dynamic_obstacles_awswh.json")
with open(cj, "w") as fh:
    json.dump(contract, fh, indent=2)
world = world_from_mjcf(os.path.join(W, "aws_warehouse.xml"))
movers, _ = load_dynamic_obstacles(cj)
world_to_sdf(world, os.path.join(W, "swarm_world_awswh.sdf"), WAYPOINTS[-1],
             goal_r=0.8, movers=movers,
             comment="AUTO-GENERATED by tools/make_validation_world.py from "
                     "aws_warehouse.xml: collision geometry sliced at z in [0.03, 0.35] m")
print(f"wrote swarm_world_awswh.sdf ({len(world.boxes)} boxes, {len(world.circles)} cylinders) "
      f"and dynamic_obstacles_awswh.json")
