function run_wh(algo, sg, seed, name, formation, spacing)
%RUN_WH  One mission on the AWS-warehouse validation scenario (MATLAB side).
%   Start point and scatter radius come from the contract JSON, like the
%   waypoint route, so both stacks read ONE scenario file.
if nargin < 5, formation = 'square'; end
if nargin < 6, spacing = 1.18; end
c = jsondecode(fileread('dynamic_obstacles_awswh.json'));
CFG_OVERRIDE = struct('algo', algo, 'seed', seed, 'run_name', name, ...
  'world_file', 'swarm_world_awswh.sdf', 'dynamic_json', 'dynamic_obstacles_awswh.json', ...
  'start_point', c.start(:)', 'scatter_center', c.start(:)', 'scatter_radius', c.scatter_radius, ...
  'formation', formation, 'grid_spacing', spacing, 'auto_fix_spacing', false, ...
  'interactive', false, 'timesteps', 3000, 'viz', struct('enable', false), ...
  'log', struct('enable', true, 'file', fullfile('logs', [name '.csv'])));
CFG_OVERRIDE.vfh = struct('sense', struct('kind','lidar','sigma0',sg,'k_rng',0.03, ...
  'fov_deg',60,'max_range',inf,'frame','body'), 'n_beams', 288);
Simulation8_dynamic;
fprintf('RESULT %s reached=%d t=%.1f minclr=%.3f coll_s=%d coll_m=%d rej=%d esc=%d\n', name, ...
  S.reached_goal, S.total_time, S.min_clearance, S.coll_static, S.coll_mover, S.n_reject, S.n_escape);
end
