#!/usr/bin/env python3
"""Seeded generator for the E13 randomised layouts and the E11 dense contract.

    python3 matlab/make_random_worlds.py            # writes rand01..rand10

Each layout is a 30 m x 16 m walled floor with N compact obstacles (posts and
crates) placed uniformly at random, rejected until
  * the start ring, the start point and the goal pad are clear,
  * obstacles do not touch each other,
  * the corridor bottleneck from start to goal is >= MIN_BOTTLENECK
    (so the rigid 2x2 payload at s = 1.18 m, swept radius 1.014 m, fits), and
  * the straight start->goal line is blocked (the mission is not trivial).
Two crossing movers per layout, also random. Everything is a function of the
layout index, so the worlds are reproducible; they are committed to the repo
and never regenerated during an experiment.
"""
import json
import os
from collections import deque

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
N_LAYOUTS = 10
MIN_BOTTLENECK = 1.30
START, GOAL = (-12.0, 0.0), (12.0, 0.0)

HEAD = """<?xml version="1.0" ?>
<!--
  {name} - RANDOMISED LAYOUT #{k} (30 m x 16 m), generated by
  make_random_worlds.py with seed {seed}. {n} compact obstacles placed
  uniformly at random subject to: clear start ring and goal pad, corridor
  bottleneck {bn:.2f} m (>= {mb:.2f}), straight start-goal line blocked.
  Same bounds, start (-12, 0) and goal pad (12, 0) as every other world.
-->
<sdf version="1.8">
  <world name="default">
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows><pose>0 0 12 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.2 -0.9</direction>
    </light>
    <model name="ground_plane"><static>true</static><link name="link">
      <collision name="c"><geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry></collision>
      <visual name="v"><geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry></visual></link></model>
"""


def box(n, x, y, sx, sy, h=1.5, col="0.45 0.45 0.5"):
    return (f'    <model name="{n}"><static>true</static><pose>{x:.3f} {y:.3f} {h/2} 0 0 0</pose><link name="l">\n'
            f'      <collision name="c"><geometry><box><size>{sx} {sy} {h}</size></box></geometry></collision>\n'
            f'      <visual name="v"><geometry><box><size>{sx} {sy} {h}</size></box></geometry>\n'
            f'        <material><ambient>{col} 1</ambient><diffuse>{col} 1</diffuse></material></visual></link></model>\n')


def cyl(n, x, y, r, h=1.5, col="0.3 0.3 0.6"):
    return (f'    <model name="{n}"><static>true</static><pose>{x:.3f} {y:.3f} {h/2} 0 0 0</pose><link name="l">\n'
            f'      <collision name="c"><geometry><cylinder><radius>{r}</radius><length>{h}</length></cylinder></geometry></collision>\n'
            f'      <visual name="v"><geometry><cylinder><radius>{r}</radius><length>{h}</length></cylinder></geometry>\n'
            f'        <material><ambient>{col} 1</ambient><diffuse>{col} 1</diffuse></material></visual></link></model>\n')


def dist(P, obs):
    """Signed distance of points P (N,2) to walls + obstacles."""
    P = np.atleast_2d(P)
    d = np.minimum.reduce([P[:, 0] + 14.85, 14.85 - P[:, 0],
                           P[:, 1] + 7.85, 7.85 - P[:, 1]])
    for kind, x, y, s in obs:
        if kind == "c":
            dk = np.hypot(P[:, 0] - x, P[:, 1] - y) - s
        else:
            qx = np.abs(P[:, 0] - x) - s / 2
            qy = np.abs(P[:, 1] - y) - s / 2
            dk = np.hypot(np.maximum(qx, 0), np.maximum(qy, 0)) + np.minimum(np.maximum(qx, qy), 0)
        d = np.minimum(d, dk)
    return d


def bottleneck(obs, res=0.1):
    xs = np.arange(-15, 15 + 1e-9, res)
    ys = np.arange(-8, 8 + 1e-9, res)
    X, Y = np.meshgrid(xs, ys)
    D = dist(np.c_[X.ravel(), Y.ravel()], obs).reshape(X.shape)
    idx = lambda p: (int(round((p[1] + 8) / res)), int(round((p[0] + 15) / res)))  # noqa: E731
    s, g = idx(START), idx(GOAL)

    def ok(th):
        free = D > th
        if not free[s] or not free[g]:
            return False
        seen = np.zeros_like(free)
        q = deque([s])
        seen[s] = True
        while q:
            i, j = q.popleft()
            if (i, j) == g:
                return True
            for di, dj in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                a, b = i + di, j + dj
                if 0 <= a < free.shape[0] and 0 <= b < free.shape[1] and free[a, b] and not seen[a, b]:
                    seen[a, b] = True
                    q.append((a, b))
        return False

    lo, hi = 0.0, 4.0
    for _ in range(10):
        m = (lo + hi) / 2
        lo, hi = (m, hi) if ok(m) else (lo, m)
    return lo


def make_layout(k):
    seed = 1000 + k
    rng = np.random.default_rng(seed)
    ring = np.array([[-9.8, 0], [-12, 2.2], [-14.2, 0], [-12, -2.2], START, GOAL])
    line = np.c_[np.linspace(-12, 12, 300), np.zeros(300)]
    while True:
        n = int(rng.integers(12, 19))
        obs = []
        tries = 0
        while len(obs) < n and tries < 4000:
            tries += 1
            kind = "c" if rng.random() < 0.6 else "b"
            s = 0.5 if kind == "c" else 0.9
            x, y = rng.uniform(-8.0, 9.0), rng.uniform(-6.6, 6.6)
            ext = s if kind == "c" else s * 0.71
            if any(np.hypot(x - o[1], y - o[2]) < ext + (o[3] if o[0] == "c" else o[3] * 0.71) + 0.3
                   for o in obs):
                continue
            if np.hypot(x - GOAL[0], y - GOAL[1]) < 2.4:
                continue
            obs.append((kind, round(x, 2), round(y, 2), s))
        if len(obs) < n or dist(ring, obs).min() < 0.6:
            continue
        if dist(line, obs).min() > 0.6:          # straight line must be blocked
            continue
        bn = bottleneck(obs)
        if bn < MIN_BOTTLENECK:
            continue
        break
    # two crossing movers on routes that start and end clear of statics
    movers = []
    for j, x0 in enumerate(sorted(rng.uniform(-6.0, 7.0, size=2))):
        for _ in range(200):
            x = float(np.clip(x0 + rng.uniform(-1.5, 1.5), -7.5, 8.5))
            a, b = [x, -6.5], [x + float(rng.uniform(-2, 2)), 6.5]
            if dist(np.array([a, b]), obs).min() > 0.8:
                break
        if j % 2:
            a, b = b, a
        movers.append({"name": f"rand{k:02d}_mover{j+1}", "shape": "box",
                       "size": [0.7, 0.7], "radius": 0.0,
                       "route": [[round(a[0], 2), a[1]], [round(b[0], 2), b[1]]],
                       "speed": round(float(rng.uniform(0.5, 0.9)), 2),
                       "t0": round(float(rng.uniform(0, 10)), 1), "wait": 2.0, "loop": True})
    name = f"swarm_world_rand{k:02d}.sdf"
    sdf = HEAD.format(name=name, k=k, seed=seed, n=len(obs), bn=bn, mb=MIN_BOTTLENECK)
    sdf += (box("wall_n", 0, 8, 30, 0.3, 2) + box("wall_s", 0, -8, 30, 0.3, 2)
            + box("wall_e", 15, 0, 0.3, 16, 2) + box("wall_w", -15, 0, 0.3, 16, 2))
    for i, (kind, x, y, s) in enumerate(obs, 1):
        sdf += cyl(f"post{i}", x, y, s) if kind == "c" else box(f"crate{i}", x, y, s, s, 0.6, "0.4 0.28 0.12")
    for m in movers:
        sdf += box(m["name"], m["route"][0][0], m["route"][0][1], 0.7, 0.7, 0.5, "0.95 0.55 0.1")
    sdf += ('    <model name="goal_pad"><static>true</static><pose>12 0 0.01 0 0 0</pose><link name="l">\n'
            '      <visual name="v"><geometry><cylinder><radius>1.2</radius><length>0.02</length></cylinder></geometry>\n'
            '        <material><ambient>0 0.8 0 1</ambient><diffuse>0 0.9 0 1</diffuse></material></visual></link></model>\n'
            '  </world>\n</sdf>\n')
    open(os.path.join(HERE, name), "w").write(sdf)
    json.dump({"comment": f"Motion contract for {name} (generated, seed {seed}).",
               "frame": "world", "dt": 0.1, "movers": movers},
              open(os.path.join(HERE, f"dynamic_obstacles_rand{k:02d}.json"), "w"), indent=2)
    return name, len(obs), bn


def dense_contract():
    """E11: the warehouse contract plus three more movers (six in total). The
    first three are the original contract unchanged, so max_movers = 3
    reproduces the standard traffic."""
    c = json.load(open(os.path.join(HERE, "dynamic_obstacles.json")))
    c["comment"] = ("Dense-traffic contract for swarm_world_dynamic.sdf (E11). Movers 1-3 are "
                    "dynamic_obstacles.json unchanged; 4-6 are added. cfg.dyn.max_movers "
                    "selects the first N.")
    c["movers"] += [
        {"name": "mover4", "shape": "box", "size": [0.7, 0.7], "radius": 0.0,
         "route": [[3.0, -1.7], [3.0, 4.3]], "speed": 0.6, "t0": 10.0, "wait": 4.0, "loop": True},
        {"name": "mover5", "shape": "circle", "size": [1.0, 1.0], "radius": 0.5,
         "route": [[-9.0, 4.3], [9.5, 4.3]], "speed": 0.6, "t0": 0.0, "wait": 3.0, "loop": True},
        {"name": "mover6", "shape": "box", "size": [0.7, 0.7], "radius": 0.0,
         "route": [[-3.5, -4.4], [-3.5, 1.9]], "speed": 0.5, "t0": 6.0, "wait": 2.0, "loop": True},
    ]
    json.dump(c, open(os.path.join(HERE, "dynamic_obstacles_dense.json"), "w"), indent=2)


if __name__ == "__main__":
    for k in range(1, N_LAYOUTS + 1):
        print("%s: %d obstacles, bottleneck %.2f m" % make_layout(k))
    dense_contract()
    print("dynamic_obstacles_dense.json: 6 movers")
